#include "periph/i2c.h"

I2C_HandleTypeDef __I2C1_HANDLE = {};

HAL_StatusTypeDef I2C1_init(void) {  
  GPIO_InitTypeDef gpio_config = {
    // PB6 as I2C1_SCL
    // PB7 as I2C1_SDA
    .Pin = GPIO_PIN_6 | GPIO_PIN_7,
    .Mode = GPIO_MODE_AF_OD,
    .Pull = GPIO_NOPULL,
    .Alternate = GPIO_AF4_I2C1
  };
  HAL_GPIO_Init(GPIOB, &gpio_config);

  RCC_PeriphCLKInitTypeDef clk_config = {
    .PeriphClockSelection = RCC_PERIPHCLK_I2C1,
    .I2c1ClockSelection = RCC_I2C1CLKSOURCE_PCLK1
  };
  if (HAL_RCCEx_PeriphCLKConfig(&clk_config) != HAL_OK) {
    return HAL_ERROR;
  }

  I2C_HandleTypeDef handle = {
    .Instance = I2C1,
    .Init = {
      .Timing = 0x10D19CE4, // generated by STM32CubeMX
      .OwnAddress1 = 0,
      .OwnAddress2 = 0,
      .OwnAddress2Masks = I2C_OA2_NOMASK,
      .DualAddressMode = I2C_DUALADDRESS_DISABLE,
      .AddressingMode = I2C_ADDRESSINGMODE_7BIT,
      .DualAddressMode = I2C_DUALADDRESS_DISABLE,
      .GeneralCallMode = I2C_GENERALCALL_ENABLE
    }
  };
  if (
    HAL_I2C_Init(&handle) != HAL_OK
    || HAL_I2CEx_ConfigAnalogFilter(&handle, I2C_ANALOGFILTER_ENABLE) != HAL_OK
    || HAL_I2CEx_ConfigDigitalFilter(&handle, 0) != HAL_OK
  ) {
    return HAL_ERROR;
  }

  __I2C1_HANDLE = handle;
  return HAL_OK;
}

HAL_StatusTypeDef I2C1_teardown(void) {
  if (HAL_I2C_DeInit(&__I2C1_HANDLE) != HAL_OK) {
    return HAL_ERROR;
  }

  HAL_GPIO_DeInit(GPIOB, GPIO_PIN_6 | GPIO_PIN_7);
  return HAL_OK;
}